#!/usr/bin/env python3
"""Lossless factory mip-bank packer and conservative 1 MiB backup patcher."""
import argparse, hashlib, json, re, struct, zlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
START, SIZE, HEADER = 0x97000, 0x40000, 256
MAGIC = b'PWMTBL01'
LENGTHS = [2048 >> shift for shift in range(1, 11)]
OFFSETS = []
pos = HEADER
for length in LENGTHS:
    OFFSETS.append(pos)
    pos += 8 * 8 * length * 2
assert pos == SIZE

def source_payload():
    text = (ROOT / 'fm1/app/pw_mip_tables.h').read_text()
    chunks = []
    for i, length in enumerate(LENGTHS, 1):
        match = re.search(r'static const int16_t pw_wt_mip'+str(i)+r'\[8\]\[8\]\['+str(length)+r'\]=\{(.*?)\n\};', text, re.S)
        if not match:
            raise ValueError(f'missing mip {i}')
        body = re.sub(r'/\*.*?\*/', '', match[1], flags=re.S)
        values = [int(n) for n in re.findall(r'-?\d+', body)]
        if len(values) != 64 * length:
            raise ValueError(f'mip {i} count {len(values)}')
        chunks.append(struct.pack('<'+'h'*len(values), *values))
    return b''.join(chunks)

def make_bank():
    payload = source_payload()
    h = bytearray(HEADER)
    h[:8] = MAGIC
    struct.pack_into('<8I', h, 8, 1, HEADER, len(payload), zlib.crc32(payload), 8, 8, 10, 2)
    struct.pack_into('<10I', h, 40, *OFFSETS)
    struct.pack_into('<10I', h, 80, *LENGTHS)
    struct.pack_into('<I', h, 252, zlib.crc32(h[:252]))
    return bytes(h) + payload

def validate(data, factory=False):
    if len(data) != SIZE or data[:8] != MAGIC:
        raise ValueError('wrong bank size or magic')
    version, header, size, crc, banks, frames, levels, width = struct.unpack_from('<8I', data, 8)
    if (version,header,size,banks,frames,levels,width) != (1,HEADER,SIZE-HEADER,8,8,10,2):
        raise ValueError('incompatible bank layout')
    if list(struct.unpack_from('<10I',data,40)) != OFFSETS or list(struct.unpack_from('<10I',data,80)) != LENGTHS:
        raise ValueError('invalid mip ranges')
    if any(data[120:252]):
        raise ValueError('unsupported reserved fields')
    if zlib.crc32(data[:252]) != struct.unpack_from('<I',data,252)[0] or zlib.crc32(data[HEADER:]) != crc:
        raise ValueError('bank checksum mismatch')
    if factory and data != make_bank():
        raise ValueError('bank differs from this source revision')
    return crc

def patch_backup(backup, bank, replace_unknown=False):
    if len(backup) != 0x100000:
        raise ValueError('input must be a complete 1 MiB backup')
    validate(bank, factory=True)
    previous = backup[START:START+SIZE]
    if previous != b'\xff'*SIZE and previous != bank:
        # This revision only recognizes its own exact factory bank, not magic alone.
        if not replace_unknown:
            raise ValueError('target contains unrecognized data; unchanged. Review the region before explicitly using --replace-unknown-data')
    result = backup[:START]+bank+backup[START+SIZE:]
    assert result[:START] == backup[:START] and result[START+SIZE:] == backup[START+SIZE:]
    return result

def write_new(path, data):
    with Path(path).open('xb') as f:
        f.write(data)

def main():
    p=argparse.ArgumentParser(description=__doc__);sub=p.add_subparsers(dest='cmd',required=True)
    sub.add_parser('generate')
    v=sub.add_parser('verify');v.add_argument('bank',type=Path)
    q=sub.add_parser('patch-backup');q.add_argument('backup',type=Path);q.add_argument('output',type=Path);q.add_argument('--bank',type=Path,default=ROOT/'data/factory-mips.pwbank');q.add_argument('--replace-unknown-data',action='store_true')
    a=p.parse_args()
    if a.cmd=='generate':
        bank=make_bank();crc=validate(bank);(ROOT/'data').mkdir(exist_ok=True)
        (ROOT/'data/factory-mips.pwbank').write_bytes(bank)
        (ROOT/'fm1/app/pw_table_layout.h').write_text('/* Generated by tools/wavetable_bank.py; do not edit. */\n#pragma once\n#define PW_TABLE_FLASH_START 0x97000u\n#define PW_TABLE_BYTES 262144u\n#define PW_TABLE_HEADER_BYTES 256u\n#define PW_TABLE_PAYLOAD_CRC 0x%08xu\n#define PW_TABLE_OFFSETS {%s}\n#define PW_TABLE_LENGTHS {%s}\n' % (crc,','.join(str(x)+'u' for x in OFFSETS),','.join(str(x)+'u' for x in LENGTHS)))
        (ROOT/'data/factory-mips.json').write_text(json.dumps(dict(format='PWMTBL01',version=1,flash_start=START,flash_end_exclusive=START+SIZE,bytes=SIZE,payload_bytes=SIZE-HEADER,payload_crc32=f'{crc:08x}',sha256=hashlib.sha256(bank).hexdigest(),mip_offsets=OFFSETS,mip_lengths=LENGTHS,encoding='signed 16-bit little endian, mip/bank/frame/sample order'),indent=2)+'\n')
        print(f'Generated {len(bank)} bytes; original samples unchanged; CRC32 {crc:08x}')
    elif a.cmd=='verify':
        validate(a.bank.read_bytes(),factory=True);print('PASS: exact factory bank, layout and checksums')
    else:
        original=a.backup.read_bytes();result=patch_backup(original,a.bank.read_bytes(),a.replace_unknown_data)
        if a.output.resolve()==a.backup.resolve():raise ValueError('output must not be the input backup')
        write_new(a.output,result)
        print('Patched only 0x97000–0xD6FFF. Application, calibration and other sectors unchanged. This does not install TEST47 firmware.')
if __name__=='__main__':
    try:main()
    except (ValueError,OSError) as e:raise SystemExit(str(e))
