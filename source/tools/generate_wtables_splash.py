#!/usr/bin/env python3
"""Encode the approved loading artwork for the existing RGB565 FM1 canvas.

The source art is retained at assets/splash/wtables-approved.png. Firmware
uses a four-colour row RLE stream, avoiding a second framebuffer or a raw
115,200-byte RGB565 image. Pillow is needed only to regenerate the header.
The progress-bar rectangle is drawn at runtime; it is not a frozen bitmap.
"""

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
COLOURS = ((0, 0, 0), (255, 255, 255), (0, 229, 235), (169, 85, 232))
BAR = (36, 202, 168, 10)


def main():
    original = Image.open(ROOT / "assets/splash/wtables-approved.png").convert("RGB")
    reduced = original.resize((240, 240), Image.Resampling.LANCZOS)
    pixels = []
    for y in range(240):
      for x in range(240):
        r, g, b = reduced.getpixel((x, y))
        # No dithering: crisp lettering and sparse flat colours compress well.
        # Neutral antialiasing belongs to black/white, not the purple palette
        # entry that happens to be closer to some mid-grey edge pixels.
        if max(r, g, b) - min(r, g, b) < 48:
            pixels.append(1 if r + g + b >= 384 else 0)
        else:
            pixels.append(min((0, 2, 3), key=lambda i:
                (r - COLOURS[i][0]) ** 2 + (g - COLOURS[i][1]) ** 2 + (b - COLOURS[i][2]) ** 2))
    # Exclude the entire reference progress bar; the same bounds are drawn
    # below using the actual elapsed startup time.
    for y in range(200, 215):
        for x in range(34, 206):
            pixels[y * 240 + x] = 0

    encoded = bytearray()
    for y in range(240):
        row = pixels[y * 240:(y + 1) * 240]
        x = 0
        while x < 240:
            colour, length = row[x], 1
            while x + length < 240 and length < 64 and row[x + length] == colour:
                length += 1
            encoded.append((colour << 6) | (length - 1))
            x += length
    # Verify lossless decoding of the device palette before emitting C.
    decoded = []
    for value in encoded:
        decoded.extend([value >> 6] * ((value & 63) + 1))
    assert decoded == pixels and len(decoded) == 57600
    assert len(encoded) < 18000, "Splash asset exceeds its reserved flash allowance"

    preview = Image.new("RGB", (240, 240))
    preview.putdata([COLOURS[p] for p in pixels])
    preview.save(ROOT / "assets/splash/wtables-background-240.png")
    rows = ["    " + ", ".join(f"0x{v:02x}" for v in encoded[i:i + 16]) + ","
            for i in range(0, len(encoded), 16)]
    header = '''/* Generated by tools/generate_wtables_splash.py; do not hand edit.
 * Approved option 2 artwork; deliberately contains no release label.
 * Four-colour row RLE: upper 2 bits = colour, lower 6 bits = length - 1.
 */
#ifndef WT_SPLASH_ART_H
#define WT_SPLASH_ART_H

#define WT_SPLASH_DURATION_MS 6000u
#define WT_SPLASH_PROGRESS_X 36u
#define WT_SPLASH_PROGRESS_Y 202u
#define WT_SPLASH_PROGRESS_W 168u
#define WT_SPLASH_PROGRESS_H 10u

static const uint8_t wt_splash_rle[] = {
''' + "\n".join(rows) + '''
};

/* Uses the application's existing 240 x 240 canvas; no extra RAM buffer. */
static void wt_splash_draw(unsigned elapsed_ms)
{
    static const uint16_t palette[4] = {
        RGB(0,0,0), RGB(255,255,255), RGB(0,229,235), RGB(169,85,232)
    };
    const uint8_t *src = wt_splash_rle;
    cv_begin(240, 240, C_BLACK);
    for (unsigned y = 0; y < 240; ++y) {
        unsigned x = 0;
        while (x < 240) {
            unsigned run = *src++, n = (run & 63u) + 1u, colour = run >> 6;
            if (colour) cv_rect(x, y, n, 1, palette[colour]);
            x += n;
        }
    }
    if (elapsed_ms > WT_SPLASH_DURATION_MS) elapsed_ms = WT_SPLASH_DURATION_MS;
    const unsigned filled = elapsed_ms * (WT_SPLASH_PROGRESS_W - 4u) / WT_SPLASH_DURATION_MS;
    cv_rect(WT_SPLASH_PROGRESS_X, WT_SPLASH_PROGRESS_Y,
            WT_SPLASH_PROGRESS_W, WT_SPLASH_PROGRESS_H, C_WHITE);
    cv_rect(WT_SPLASH_PROGRESS_X + 2, WT_SPLASH_PROGRESS_Y + 2,
            WT_SPLASH_PROGRESS_W - 4, WT_SPLASH_PROGRESS_H - 4, C_BLACK);
    if (filled) cv_rect(WT_SPLASH_PROGRESS_X + 2, WT_SPLASH_PROGRESS_Y + 2,
            filled, WT_SPLASH_PROGRESS_H - 4, palette[2]);
    cv_blit(0, 0);
}
#endif
'''
    (ROOT / "fm1/app/splash_wtables.h").write_text(header)
    print(f"Encoded approved 240x240 splash: {len(encoded)} bytes (raw RGB565: 115200)")


if __name__ == "__main__":
    main()
